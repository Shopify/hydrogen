import type { AgentStep } from "./agent";
import type { ClickTarget } from "./recorder";
import type { AddToCartTask } from "./task";

type ScriptStep = {
  readonly label: string;
  readonly code: string;
  /** Path and query the click led to, when it navigated; replay waits for it before moving on. */
  readonly thenUrl?: string;
};

/** Max distance in CSS pixels between an agent click and the DOM click it produced. */
const CLICK_MATCH_TOLERANCE_PX = 6;

const CLICK_COUNTS: Record<string, number> = { click: 1, doubleClick: 2, tripleClick: 3 };

// Claude computer-use key names to Playwright key names.
const KEY_NAMES: Record<string, string> = {
  return: "Enter",
  enter: "Enter",
  backspace: "Backspace",
  escape: "Escape",
  esc: "Escape",
  tab: "Tab",
  space: "Space",
  delete: "Delete",
  ctrl: "Control",
  control: "Control",
  cmd: "Meta",
  super: "Meta",
  alt: "Alt",
  shift: "Shift",
  up: "ArrowUp",
  down: "ArrowDown",
  left: "ArrowLeft",
  right: "ArrowRight",
};

/**
 * Turns a passing agent run into a deterministic Playwright spec. Clicks become role-based
 * locators from the recorded click targets, falling back to coordinates; typing and key presses
 * replay as keyboard input. Scrolls, waits and screenshots are dropped: locators scroll and wait.
 */
export function generateSpec(options: {
  readonly task: AddToCartTask;
  readonly startPath: string;
  readonly startLabel: string;
  readonly steps: readonly AgentStep[];
  readonly clicks: readonly ClickTarget[];
  readonly model: string;
}): string {
  const { task, startPath, startLabel, steps, clicks, model } = options;
  const pairs = pairClicks(steps, clicks);
  const scriptSteps = steps.flatMap((step, index): ScriptStep[] => {
    const clickCount = CLICK_COUNTS[step.action];
    if (clickCount !== undefined) {
      const target = pairs.get(index);
      return [{ ...clickStep(target, step, clickCount), ...thenUrlFor(index, target, pairs) }];
    }
    if (step.action === "type" && typeof step.args.text === "string") {
      return [
        { label: `type ${q(step.args.text)}`, code: `page.keyboard.type(${q(step.args.text)})` },
      ];
    }
    if (step.action === "keypress") {
      const keys = Array.isArray(step.args.keys) ? step.args.keys : [step.args.text];
      return keys
        .filter((key): key is string => typeof key === "string")
        .map((key) => ({
          label: `press ${key}`,
          code: `page.keyboard.press(${q(toPlaywrightKey(key))})`,
        }));
    }
    return [];
  });

  const body = scriptSteps
    .map((s) => {
      const stepOptions = s.thenUrl ? `, { thenUrl: ${q(s.thenUrl)} }` : "";
      return `  await replay.step(${q(s.label)}, (page) => ${s.code}${stepOptions});`;
    })
    .join("\n");

  return `// Generated by @shopify/storefront-agent-e2e from a passing agent run. Do not edit by hand:
// regenerate instead (node scripts/generated-tests.ts generate --start ${startLabel}).
// Agent goal: ${oneLine(task.goal)}
// Model: ${model}. Generated: ${new Date().toISOString()}.
import type { AddToCartTask } from "../src/task";
import { test } from "../src/replay";

const task: AddToCartTask = ${JSON.stringify(task, null, 2)};

test(${q(`add to cart from ${startLabel}`)}, async ({ replay }) => {
  await replay.start(${q(startPath)});
${body}
  await replay.finish(task);
});
`;
}

// Pairs each agent click step with the DOM click it produced: the nearest recorded click at the
// same coordinates, scanning forward only. Extra or missing DOM clicks can't shift later steps.
function pairClicks(
  steps: readonly AgentStep[],
  clicks: readonly ClickTarget[],
): Map<number, ClickTarget> {
  const pairs = new Map<number, ClickTarget>();
  let cursor = 0;
  steps.forEach((step, index) => {
    if (CLICK_COUNTS[step.action] === undefined) return;
    const x = Number(step.args.x);
    const y = Number(step.args.y);
    for (let i = cursor; i < clicks.length; i++) {
      const click = clicks[i];
      if (
        click &&
        Math.abs(click.x - x) <= CLICK_MATCH_TOLERANCE_PX &&
        Math.abs(click.y - y) <= CLICK_MATCH_TOLERANCE_PX
      ) {
        pairs.set(index, click);
        cursor = i + 1;
        return;
      }
    }
  });
  return pairs;
}

// The page the next recorded click happened on is where this click led. If it differs, replay
// must wait for it, or the next click can land on the old page.
function thenUrlFor(
  index: number,
  target: ClickTarget | undefined,
  pairs: Map<number, ClickTarget>,
) {
  if (!target) return {};
  const next = [...pairs.entries()].find(([stepIndex]) => stepIndex > index)?.[1];
  if (!next) return {};
  const before = pathAndQuery(target.url);
  const after = pathAndQuery(next.url);
  return before === after ? {} : { thenUrl: after };
}

function pathAndQuery(url: string): string {
  const parsed = new URL(url);
  return `${parsed.pathname}${parsed.search}`;
}

function oneLine(text: string): string {
  return text.replaceAll(/[\r\n]+/g, " ");
}

function clickStep(
  target: ClickTarget | undefined,
  step: AgentStep,
  clickCount: number,
): ScriptStep {
  const locator = target ? locatorFor(target) : null;
  if (target && locator) {
    return { label: `click ${describe(target)}`, code: `${locator}.${locatorClick(clickCount)}` };
  }
  return coordinateClick(target, step, clickCount);
}

function locatorClick(clickCount: number): string {
  if (clickCount === 2) return "dblclick()";
  return clickCount === 3 ? "click({ clickCount: 3 })" : "click()";
}

function coordinateClick(
  target: ClickTarget | undefined,
  step: AgentStep,
  clickCount: number,
): ScriptStep {
  const x = Number(target?.x ?? step.args.x ?? 0);
  const y = Number(target?.y ?? step.args.y ?? 0);
  const options = clickCount > 1 ? `, { clickCount: ${clickCount} }` : "";
  const what = target ? ` on ${describe(target)}` : "";
  return {
    label: `click at ${x},${y}${what} (not interactive)`,
    code: `page.mouse.click(${x}, ${y}${options})`,
  };
}

// Only interactive elements get a locator. Clicks on plain text or containers are usually
// incidental (focusing, tapping a title) and their text often changes (counts, prices), so they
// replay as coordinate clicks instead.
function locatorFor(target: ClickTarget): string | null {
  if (!target.role) return null;
  const scope = scopeFor(target);
  const nth = target.nth === null ? "" : `.nth(${target.nth})`;
  const name = target.name ? `, { name: ${q(target.name)} }` : "";
  return `${scope}.getByRole(${q(target.role)}${name})${nth}`;
}

function scopeFor(target: ClickTarget): string {
  switch (target.scope.kind) {
    case "page":
      return "page";
    case "dialog":
      return target.scope.name
        ? `page.getByRole("dialog", { name: ${q(target.scope.name)} })`
        : `page.getByRole("dialog")`;
    case "landmark":
      return `page.getByRole(${q(target.scope.role)})`;
  }
}

function describe(target: ClickTarget): string {
  const what = `${target.role ?? "element"} ${q(target.name || target.text)}`;
  switch (target.scope.kind) {
    case "page":
      return what;
    case "dialog":
      return `${what} in dialog ${q(target.scope.name)}`;
    case "landmark":
      return `${what} in ${target.scope.role}`;
  }
}

function toPlaywrightKey(key: string): string {
  return key
    .split("+")
    .map(
      (part) =>
        KEY_NAMES[part.toLowerCase()] ??
        (part.length === 1 ? part : part[0]?.toUpperCase() + part.slice(1)),
    )
    .join("+");
}

function q(value: string): string {
  return JSON.stringify(value);
}
